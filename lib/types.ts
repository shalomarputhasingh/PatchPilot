// Types shared by server and client. No server-only imports here.

export type FinalStatus =
  | "VERIFIED"
  | "PARTIALLY_VERIFIED"
  | "UNVERIFIED"
  | "FAILED"
  | "BASELINE_NOT_REPRODUCED";

export type StepId =
  | "input"
  | "baseline"
  | "analysis"
  | "patch"
  | "validate"
  | "repaired"
  | "tests"
  | "final";

export type StepState = "pending" | "running" | "completed" | "failed" | "skipped";

export interface StepInfo {
  id: StepId;
  label: string;
  state: StepState;
  detail?: string;
  startedAt?: number;
  durationMs?: number;
}

export interface ExecutionResult {
  stdout: string;
  stderr: string;
  exitCode: number | null;
  signal?: string | null;
  timedOut: boolean;
  /** Wall-clock round trip measured by PatchPilot (the provider reports no duration). */
  durationMs: number;
  truncated: boolean;
  /** Set when the sandbox call itself failed (not the user's program). */
  providerError?: string;
}

export interface RegressionTest {
  name: string;
  /** Name of a top-level function in the submitted module. */
  function: string;
  args: unknown[];
  kwargs: Record<string, unknown>;
  expected: unknown;
  rationale?: string;
}

export interface TestOutcome {
  name: string;
  status: "passed" | "failed" | "error" | "not_run";
  message?: string;
  actual?: string;
}

export interface TestRun {
  /** "ran": harness produced a verdict for every test it reported. "not_run": harness unavailable. */
  ran: boolean;
  outcomes: TestOutcome[];
  execution?: ExecutionResult;
  note?: string;
}

export interface UserTestRun {
  ran: boolean;
  passed: boolean;
  execution?: ExecutionResult;
  note?: string;
}

export interface Diagnosis {
  summary: string;
  rootCause: string;
  reasoning: string;
  affectedLines: number[];
  limitations: string[];
  edgeCases: string[];
}

export interface Attempt {
  index: number; // 0 = initial patch, 1..2 = repairs
  kind: "initial" | "repair";
  reasoning: string;
  rawDiff: string;
  patchStatus: "applied" | "rejected";
  patchError?: string;
  /** Canonical diff regenerated by PatchPilot from original -> repaired. */
  diff?: string;
  repairedSource?: string;
  added?: number;
  removed?: number;
  repairedExecution?: ExecutionResult;
  generatedTests?: TestRun;
  userTests?: UserTestRun;
  passed: boolean;
  startedAt: number;
  durationMs?: number;
}

export type WorkflowStatus = "running" | "done" | "error";

export interface SessionView {
  id: string;
  status: WorkflowStatus;
  mode: "full" | "preview";
  createdAt: number;
  steps: StepInfo[];
  currentStep?: StepId;
  originalSource: string;
  baseline?: ExecutionResult;
  diagnosis?: Diagnosis;
  regressionTests: RegressionTest[];
  /** Generated tests executed against the ORIGINAL source (reproduction evidence). */
  baselineTests?: TestRun;
  baselineUserTests?: UserTestRun;
  attempts: Attempt[];
  repairAttemptsUsed: number;
  canRetry: boolean;
  finalStatus?: FinalStatus;
  finalReason?: string;
  reproduced?: boolean;
  notices: string[];
  error?: { code: string; message: string };
}

export interface DebugRequest {
  source: string;
  bugReport: string;
  expectedBehavior?: string;
  notes?: string;
  stdin?: string;
  userTests?: string;
}

export interface ApiError {
  error: { code: string; message: string; fields?: Record<string, string> };
}

export interface HealthView {
  ok: boolean;
  groq: { configured: boolean; model: string | null };
  sandbox: { configured: boolean; provider: string };
  mode: "full" | "preview" | "unavailable";
}
